CREATE TABLE IF NOT EXISTS "ASISTENCIA_REGISTROS" (
  "ID" BIGSERIAL PRIMARY KEY,
  "CURSO_ID" BIGINT NOT NULL REFERENCES "CURSOS" ("ID"),
  "FECHA" DATE NOT NULL,
  "ACTIVO" BOOLEAN NOT NULL DEFAULT TRUE,
  "CREADO_EN" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "ACTUALIZADO_EN" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "UQ_ASISTENCIA_REGISTROS_CURSO_FECHA" UNIQUE ("CURSO_ID", "FECHA")
);

CREATE TABLE IF NOT EXISTS "ASISTENCIA_DETALLES" (
  "ID" BIGSERIAL PRIMARY KEY,
  "REGISTRO_ID" BIGINT NOT NULL REFERENCES "ASISTENCIA_REGISTROS" ("ID") ON DELETE CASCADE,
  "ALUMNO_ID" BIGINT NOT NULL REFERENCES "ALUMNOS" ("ID"),
  "ESTADO" VARCHAR(20) NOT NULL,
  "HORA_LLEGADA" TIME NULL,
  "OBSERVACION" VARCHAR(255) NULL,
  "ACTIVO" BOOLEAN NOT NULL DEFAULT TRUE,
  "CREADO_EN" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "ACTUALIZADO_EN" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "UQ_ASISTENCIA_DETALLES_REGISTRO_ALUMNO" UNIQUE ("REGISTRO_ID", "ALUMNO_ID")
);

DELETE FROM "ASISTENCIA_DETALLES";
DELETE FROM "ASISTENCIA_REGISTROS";

