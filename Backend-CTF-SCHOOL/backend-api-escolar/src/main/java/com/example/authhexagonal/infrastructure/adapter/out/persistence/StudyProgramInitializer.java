    private void seedStudyProgram(String programCode, String classpathLocation) throws Exception {
        ClassPathResource resource = new ClassPathResource(classpathLocation);
        if (!resource.exists()) {
            LOGGER.warn("No se encontro recurso de Programa de Estudio en {}", classpathLocation);
            return;
        }

        String rawJson;
        try (InputStream inputStream = resource.getInputStream()) {
            rawJson = new String(inputStream.readAllBytes(), StandardCharsets.UTF_8);
        }

        JsonNode root = objectMapper.readTree(rawJson);
        JsonNode document = root.path("documento");

        Long programId = upsertProgram(programCode, document, root.path("oas_todas_las_unidades").path("descripcion").asText(null), rawJson);
        clearProgramChildren(programId);

        insertAxes(programId, document.path("ejes"));
        insertGlobalAttitudes(programId, root.path("actitudes"));

        Map<String, Long> objectiveIds = insertObjectiveCatalog(programId, root.path("objetivos_de_aprendizaje"));
        insertPermanentObjectives(programId, root.path("oas_todas_las_unidades"), objectiveIds);
        insertUnits(programId, root.path("unidades"), objectiveIds);
    }

    private Long upsertProgram(String programCode, JsonNode document, String permanentDescription, String rawJson) {
        Long existingId = jdbcTemplate.query("""
                SELECT "ID"
                FROM "PROGRAMAS_ESTUDIO"
                WHERE "CODIGO" = ?
                """, (rs, rowNum) -> rs.getLong("ID"), programCode).stream().findFirst().orElse(null);

        String subject = document.path("asignatura").asText("");
        String grade = document.path("grado").asText("");

        if (existingId == null) {
            return jdbcTemplate.queryForObject("""
                    INSERT INTO "PROGRAMAS_ESTUDIO" (
                        "CODIGO",
                        "ASIGNATURA",
                        "ASIGNATURA_NORMALIZADA",
                        "GRADO",
                        "GRADO_NORMALIZADO",
                        "DECRETO",
                        "FUENTE",
                        "ISBN",
                        "EDICION",
                        "TOTAL_UNIDADES",
                        "TOTAL_OAS",
                        "HORAS_TOTALES",
                        "DESCRIPCION_OAS_PERMANENTES",
                        "CONTENIDO_JSON",
                        "ACTIVO"
                    )
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, CAST(? AS jsonb), TRUE)
                    RETURNING "ID"
                    """, Long.class,
                    programCode,
                    subject,
                    normalize(subject),
                    grade,
                    normalizeGrade(grade),
                    nullIfBlank(document.path("decreto").asText(null)),
                    nullIfBlank(document.path("fuente").asText(null)),
                    nullIfBlank(document.path("isbn").asText(null)),
                    nullIfBlank(document.path("edicion").asText(null)),
                    nullableInt(document.path("total_unidades")),
                    nullableInt(document.path("total_oas")),
                    nullableInt(document.path("horas_total")),
                    nullIfBlank(permanentDescription),
                    rawJson
            );
        }

        jdbcTemplate.update("""
                UPDATE "PROGRAMAS_ESTUDIO"
                SET "ASIGNATURA" = ?,
                    "ASIGNATURA_NORMALIZADA" = ?,
                    "GRADO" = ?,
                    "GRADO_NORMALIZADO" = ?,
                    "DECRETO" = ?,
                    "FUENTE" = ?,
                    "ISBN" = ?,
                    "EDICION" = ?,
                    "TOTAL_UNIDADES" = ?,
                    "TOTAL_OAS" = ?,
                    "HORAS_TOTALES" = ?,
                    "DESCRIPCION_OAS_PERMANENTES" = ?,
                    "CONTENIDO_JSON" = CAST(? AS jsonb),
                    "ACTIVO" = TRUE,
                    "FECHA_ACTUALIZACION" = CURRENT_TIMESTAMP
                WHERE "ID" = ?
                """,
                subject,
                normalize(subject),
                grade,
                normalizeGrade(grade),
                nullIfBlank(document.path("decreto").asText(null)),
                nullIfBlank(document.path("fuente").asText(null)),
                nullIfBlank(document.path("isbn").asText(null)),
                nullIfBlank(document.path("edicion").asText(null)),
                nullableInt(document.path("total_unidades")),
                nullableInt(document.path("total_oas")),
                nullableInt(document.path("horas_total")),
                nullIfBlank(permanentDescription),
                rawJson,
                existingId
        );
        return existingId;
    }

    private void clearProgramChildren(Long programId) {
        jdbcTemplate.update("""
                DELETE FROM "PROGRAMAS_ESTUDIO_ACTITUDES"
                WHERE "PROGRAMA_ID" = ?
                """, programId);
        jdbcTemplate.update("""
                DELETE FROM "PROGRAMAS_ESTUDIO_LECTURAS"
                WHERE "UNIDAD_ID" IN (
                    SELECT "ID" FROM "PROGRAMAS_ESTUDIO_UNIDADES" WHERE "PROGRAMA_ID" = ?
                )
                """, programId);
        jdbcTemplate.update("""
                DELETE FROM "PROGRAMAS_ESTUDIO_UNIDADES"
                WHERE "PROGRAMA_ID" = ?
                """, programId);
        jdbcTemplate.update("""
                DELETE FROM "PROGRAMAS_ESTUDIO_OAS_PERMANENTES"
                WHERE "PROGRAMA_ID" = ?
                """, programId);
        jdbcTemplate.update("""
                DELETE FROM "PROGRAMAS_ESTUDIO_OA_SUBITEMS"
                WHERE "OA_ID" IN (
                    SELECT "ID" FROM "PROGRAMAS_ESTUDIO_OAS" WHERE "PROGRAMA_ID" = ?
                )
                """, programId);
        jdbcTemplate.update("""
                DELETE FROM "PROGRAMAS_ESTUDIO_OAS"
                WHERE "PROGRAMA_ID" = ?
                """, programId);
        jdbcTemplate.update("""
                DELETE FROM "PROGRAMAS_ESTUDIO_EJES"
                WHERE "PROGRAMA_ID" = ?
                """, programId);
    }

    private void insertAxes(Long programId, JsonNode axesNode) {
        int order = 1;
        for (String axis : extractTextList(axesNode)) {
            jdbcTemplate.update("""
                    INSERT INTO "PROGRAMAS_ESTUDIO_EJES" ("PROGRAMA_ID", "ORDEN", "NOMBRE")
                    VALUES (?, ?, ?)
                    """, programId, order++, axis);
        }
    }

    private void insertGlobalAttitudes(Long programId, JsonNode attitudesNode) {
        int order = 1;
        for (JsonNode attitudeNode : iterable(attitudesNode)) {
            jdbcTemplate.update("""
                    INSERT INTO "PROGRAMAS_ESTUDIO_ACTITUDES" (
                        "PROGRAMA_ID",
                        "UNIDAD_ID",
                        "ORDEN",
                        "CODIGO",
                        "DESCRIPCION"
                    )
                    VALUES (?, NULL, ?, ?, ?)
                    """,
                    programId,
                    order++,
                    nullIfBlank(attitudeNode.path("codigo").asText(null)),
                    nullIfBlank(attitudeNode.path("descripcion").asText(null))
            );
        }
    }

    private Map<String, Long> insertObjectiveCatalog(Long programId, JsonNode objectivesNode) {
        Map<String, Long> objectiveIds = new LinkedHashMap<>();
        int order = 1;
        for (JsonNode objectiveNode : iterable(objectivesNode)) {
            String code = objectiveNode.path("codigo").asText(null);
            if (code == null || code.isBlank()) {
                continue;
            }
            Long objectiveId = jdbcTemplate.queryForObject("""
                    INSERT INTO "PROGRAMAS_ESTUDIO_OAS" (
                        "PROGRAMA_ID",
                        "ORDEN",
                        "CODIGO",
                        "EJE",
                        "DESCRIPCION"
                    )
                    VALUES (?, ?, ?, ?, ?)
                    RETURNING "ID"
                    """, Long.class,
                    programId,
                    order++,
                    code,
                    nullIfBlank(objectiveNode.path("eje").asText(null)),
                    coalesceObjectiveDescription(objectiveNode)
            );
            objectiveIds.put(code, objectiveId);
            insertSubItems("PROGRAMAS_ESTUDIO_OA_SUBITEMS", "OA_ID", objectiveId, objectiveNode.path("sub_items"));
        }
        return objectiveIds;
    }

